import { describe, expect, it } from "vitest";
import { runCli, validateHeader } from "./conventional-commit.mjs";

describe("validateHeader", () => {
  it.each([
    "feat: agregar notas de voz",
    "feat(bot): registrar gastos desde notas de voz",
    "fix(whatsapp): ignorar saltos de línea en el token",
    "refactor(transacciones): separar consultas y acciones",
    "test: cubrir el webhook",
    "docs: explicar el flujo de pull requests",
    "chore(deps): actualizar next a 16.5",
    "ci: validar el título del PR",
    "perf(db): agregar índice por fecha",
    "feat(auth)!: exigir verificación del correo",
    "fix: ¿por qué falla el balance? corregir zona horaria",
    "docs: añadir sección de pruebas",
  ])("acepta %j", (title) => {
    expect(validateHeader(title)).toEqual({ ok: true });
  });

  it.each([
    ["Agregar notas de voz", "formato"],
    ["feature: agregar notas", "Tipo"],
    ["feat(Bot): agregar notas", "Ámbito"],
    ["feat(bot whatsapp): agregar", "Ámbito"],
    ["feat: Agregar notas de voz", "minúscula"],
    ["feat: Ánimo en la descripción", "minúscula"],
    ["feat: agregar notas de voz.", "punto"],
    ["feat:agregar notas", "formato"],
    ["feat: ", "descripción"],
    [`feat: ${"a".repeat(80)}`, "Máximo"],
  ])("rechaza %j (%s)", (title, expectedError) => {
    const result = validateHeader(title);
    expect(result.ok).toBe(false);
    expect(!result.ok && result.errors.join(" ")).toContain(expectedError);
  });

  it("permite otro largo máximo (títulos de Dependabot)", () => {
    const title = "chore(deps-dev): bump @typescript-eslint/eslint-plugin from 8.10.0 to 8.11.0";
    expect(validateHeader(title).ok).toBe(false);
    expect(validateHeader(title, { maxLength: 120 })).toEqual({ ok: true });
  });

  it("acepta los títulos agrupados de Dependabot", () => {
    expect(validateHeader("chore(deps): bump the menores-y-parches group with 3 updates")).toEqual({
      ok: true,
    });
    expect(validateHeader("ci(deps): bump the acciones group with 2 updates")).toEqual({
      ok: true,
    });
  });

  it("solo valida la primera línea (el cuerpo es libre)", () => {
    expect(
      validateHeader("fix: corregir el balance\n\nEl cálculo usaba UTC. Ahora usa Bogotá."),
    ).toEqual({
      ok: true,
    });
  });

  it("en los commits acepta los mensajes que genera git", () => {
    for (const msg of ['Merge branch "main"', 'Revert "feat: algo"', "fixup! feat: algo"]) {
      expect(validateHeader(msg, { allowAutogenerated: true })).toEqual({ ok: true });
      expect(validateHeader(msg).ok).toBe(false);
    }
  });
});

describe("validateHeader · detalles", () => {
  it("ignora espacios alrededor de la línea", () => {
    expect(validateHeader("  feat: agregar notas  ")).toEqual({ ok: true });
  });

  it("explica qué tipo no es válido y cuáles se aceptan", () => {
    const result = validateHeader("feature: agregar notas");
    expect(!result.ok && result.errors[0]).toBe(
      'Tipo "feature" no válido. Usa: feat, fix, refactor, test, docs, chore, ci, perf.',
    );
  });

  it("rechaza espacios de más al inicio de la descripción", () => {
    const result = validateHeader("feat:  agregar notas");
    expect(!result.ok && result.errors).toContain("Sobran espacios al inicio o al final.");
  });

  it.each([
    "algo Merge x",
    'arreglar Revert "x"',
    "algo fixup! x",
    "algo squash! x",
    "algo amend! x",
  ])("los mensajes automáticos de git solo se reconocen al inicio: %j", (message) => {
    expect(validateHeader(message, { allowAutogenerated: true }).ok).toBe(false);
  });
});

describe("runCli", () => {
  function run(argv: string[], files: Record<string, string> = {}) {
    const errors: string[] = [];
    const code = runCli(argv, {
      readFile: (path: string) => files[path],
      error: (line: string) => errors.push(line),
    });
    return { code, errors: errors.join("\n") };
  }

  it("acepta un título válido sin imprimir nada", () => {
    expect(run(["feat(bot):", "registrar", "notas"])).toEqual({ code: 0, errors: "" });
  });

  it("explica el error y muestra ejemplos", () => {
    const result = run(["Agregar notas."]);
    expect(result.code).toBe(1);
    expect(result.errors).toContain(
      '✗ El título del PR no sigue Conventional Commits:\n  "Agregar notas."',
    );
    expect(result.errors).toContain('  • El formato debe ser "<tipo>(<ámbito>): <descripción>".');
    expect(result.errors).toContain("feat(bot): registrar gastos desde notas de voz");
    expect(result.errors).toContain("Tipos: feat, fix, refactor, test, docs, chore, ci, perf.");
  });

  it("valida el mensaje de un commit, ignorando los comentarios de git", () => {
    const files = { "/msg": "# Comentario de git\nfix: corregir el balance\n\n# otro comentario" };
    expect(run(["--file", "/msg"], files).code).toBe(0);
    expect(run(["--file", "/merge"], { "/merge": "Merge branch 'main'" }).code).toBe(0);

    const bad = run(["--file", "/bad"], { "/bad": "Arreglos varios" });
    expect(bad.code).toBe(1);
    expect(bad.errors).toContain("✗ El mensaje del commit no sigue Conventional Commits");
  });

  it("acepta --max-length para títulos más largos", () => {
    const title = `chore(deps): ${"a".repeat(80)}`;
    expect(run([title]).code).toBe(1);
    expect(run(["--max-length", "120", title]).code).toBe(0);
    expect(run(["--max-length", "no-es-un-numero", title]).code).toBe(1);
  });
});
