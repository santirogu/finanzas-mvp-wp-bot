import { describe, expect, it } from "vitest";
import { validateHeader } from "./conventional-commit.mjs";

describe("validateHeader", () => {
  it.each([
    "feat: agregar notas de voz",
    "feat(bot): registrar gastos desde notas de voz",
    "fix(whatsapp): ignorar saltos de línea en el token",
    "refactor(transacciones): separar consultas y acciones",
    "test: cubrir el webhook",
    "docs: explicar el flujo de pull requests",
    "chore(deps): actualizar next a 16.5",
    "ci: validar el título del PR",
    "perf(db): agregar índice por fecha",
    "feat(auth)!: exigir verificación del correo",
    "fix: ¿por qué falla el balance? corregir zona horaria",
    "docs: añadir sección de pruebas",
  ])("acepta %j", (title) => {
    expect(validateHeader(title)).toEqual({ ok: true });
  });

  it.each([
    ["Agregar notas de voz", "formato"],
    ["feature: agregar notas", "Tipo"],
    ["feat(Bot): agregar notas", "Ámbito"],
    ["feat(bot whatsapp): agregar", "Ámbito"],
    ["feat: Agregar notas de voz", "minúscula"],
    ["feat: Ánimo en la descripción", "minúscula"],
    ["feat: agregar notas de voz.", "punto"],
    ["feat:agregar notas", "formato"],
    ["feat: ", "descripción"],
    [`feat: ${"a".repeat(80)}`, "Máximo"],
  ])("rechaza %j (%s)", (title, expectedError) => {
    const result = validateHeader(title);
    expect(result.ok).toBe(false);
    expect(!result.ok && result.errors.join(" ")).toContain(expectedError);
  });

  it("permite otro largo máximo (títulos de Dependabot)", () => {
    const title = "chore(deps-dev): bump @typescript-eslint/eslint-plugin from 8.10.0 to 8.11.0";
    expect(validateHeader(title).ok).toBe(false);
    expect(validateHeader(title, { maxLength: 120 })).toEqual({ ok: true });
  });

  it("acepta los títulos agrupados de Dependabot", () => {
    expect(validateHeader("chore(deps): bump the menores-y-parches group with 3 updates")).toEqual({
      ok: true,
    });
    expect(validateHeader("ci(deps): bump the acciones group with 2 updates")).toEqual({
      ok: true,
    });
  });

  it("solo valida la primera línea (el cuerpo es libre)", () => {
    expect(
      validateHeader("fix: corregir el balance\n\nEl cálculo usaba UTC. Ahora usa Bogotá."),
    ).toEqual({
      ok: true,
    });
  });

  it("en los commits acepta los mensajes que genera git", () => {
    for (const msg of ['Merge branch "main"', 'Revert "feat: algo"', "fixup! feat: algo"]) {
      expect(validateHeader(msg, { allowAutogenerated: true })).toEqual({ ok: true });
      expect(validateHeader(msg).ok).toBe(false);
    }
  });
});
