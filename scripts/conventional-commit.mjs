#!/usr/bin/env node
// Valida mensajes de commit y títulos de PR con Conventional Commits (ver CLAUDE.md):
//   <tipo>(<ámbito opcional>): <descripción en imperativo, minúscula inicial, sin punto final>
//
// Uso:
//   node scripts/conventional-commit.mjs "feat(bot): registrar notas de voz"   → valida un título
//   node scripts/conventional-commit.mjs --file .git/COMMIT_EDITMSG          → valida un commit (hook)
// Sin dependencias: corre en el CI sin instalar paquetes.

import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const TYPES = ["feat", "fix", "refactor", "test", "docs", "chore", "ci", "perf"];
export const MAX_HEADER_LENGTH = 72;

// Mensajes que genera git y no escribe una persona.
const AUTOGENERATED = [/^Merge /, /^Revert "/, /^fixup! /, /^squash! /, /^amend! /];

const HEADER = /^(?<type>[a-z]+)(?:\((?<scope>[^()]*)\))?(?<breaking>!)?: (?<description>.*)$/;

/** @returns {{ ok: true } | { ok: false, errors: string[] }} */
export function validateHeader(text, { allowAutogenerated = false } = {}) {
  const header = text.split("\n")[0].trim();
  if (allowAutogenerated && AUTOGENERATED.some((re) => re.test(header))) return { ok: true };

  const match = header.match(HEADER);
  if (!match) {
    return { ok: false, errors: ['El formato debe ser "<tipo>(<ámbito>): <descripción>".'] };
  }

  const { type, scope, description } = match.groups;
  const errors = [];
  if (!TYPES.includes(type)) errors.push(`Tipo "${type}" no válido. Usa: ${TYPES.join(", ")}.`);
  if (scope !== undefined && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(scope)) {
    errors.push(`Ámbito "${scope}" no válido: minúsculas, números y guiones (ej. "whatsapp").`);
  }
  if (!description.trim()) {
    errors.push("Falta la descripción después de los dos puntos.");
  } else {
    const first = description[0];
    if (first !== first.toLocaleLowerCase("es")) {
      errors.push("La descripción debe empezar en minúscula (ej. \"agregar…\", no \"Agregar…\").");
    }
    if (/[.。]$/.test(description)) errors.push("La descripción no debe terminar en punto.");
    if (description !== description.trim()) errors.push("Sobran espacios al inicio o al final.");
  }
  if (header.length > MAX_HEADER_LENGTH) {
    errors.push(`Máximo ${MAX_HEADER_LENGTH} caracteres (tiene ${header.length}).`);
  }
  return errors.length ? { ok: false, errors } : { ok: true };
}

function main(argv) {
  const fromFile = argv[0] === "--file";
  const raw = fromFile ? readFileSync(argv[1], "utf8") : argv.join(" ");
  // En el archivo del commit, git agrega comentarios que empiezan por "#".
  const text = raw
    .split("\n")
    .filter((line) => !line.startsWith("#"))
    .join("\n")
    .trim();
  const result = validateHeader(text, { allowAutogenerated: fromFile });
  if (result.ok) return 0;

  const label = fromFile ? "El mensaje del commit" : "El título del PR";
  console.error(`✗ ${label} no sigue Conventional Commits:\n  "${text.split("\n")[0]}"\n`);
  for (const error of result.errors) console.error(`  • ${error}`);
  console.error(
    `\nEjemplos válidos:\n  feat(bot): registrar gastos desde notas de voz\n  fix(whatsapp): reintentar el envío si Meta responde 500\n  docs: explicar el flujo de pull requests\n\nTipos: ${TYPES.join(", ")}. Más detalles en CLAUDE.md.`,
  );
  return 1;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main(process.argv.slice(2)));
}
